static const uint8_t* get_glyph(unsigned char c)
{
    /* font8x16_basic covers codepoints 32..(32+96)=128 inclusive */
    if (c < 32 || c >= (32 + 97)) {
        return font8x16_basic[0];
    }
    return font8x16_basic[c - 32];
}

void draw_char(int x, int y, char c, uint32_t color)
{
    const uint8_t* glyph = get_glyph((unsigned char)c);
    /* Render as 8x16 using the 16 bytes in each glyph row */
    for (int row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (1 << (7 - col))) {
                putpixel(x + col, y + row, color);
            }
        }
    }
}

void draw_string(int x, int y, const char* str, uint32_t color)
{
    int cursor = x;
    while (*str) {
        if (*str == '\n') {
            /* increase by 16px glyph height + 2px spacing */
            y += 18;
            cursor = x;
        } else {
            draw_char(cursor, y, *str, color);
            cursor += 8;
        }
        str++;
    }
}
